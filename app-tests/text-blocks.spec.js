import {test,expect} from '@playwright/test';
import JSZip from 'jszip';
import fs from 'node:fs/promises';

test('Text only opens a blank canvas and inserts independently styled blocks',async({page})=>{
 await page.goto('./');
 await expect(page.locator('#save')).toBeEnabled();
 await page.getByRole('button',{name:'New website',exact:true}).click();
 await page.getByRole('radio',{name:'Text only',exact:true}).check();
 await page.getByRole('button',{name:'Create website',exact:true}).click();
 const canvas=page.frameLocator('.gjs-frame');
 await expect(page.locator('#text-empty-canvas')).toBeVisible();
 await expect(canvas.locator('section, header, footer')).toHaveCount(0);
 await expect(page.getByLabel('Section category')).toHaveValue('all');
 const outline=page.getByRole('button',{name:'Add Headline · Outline Echo',exact:true});
 await expect(outline.locator('.text-preset-preview')).toContainText('Future design system');
 await outline.click();
 await expect(page.locator('#text-empty-canvas')).toBeHidden();
 await expect(canvas.locator('.tb-outline-echo h1')).toBeVisible();
 await expect(canvas.locator('.tb-outline-echo h1')).not.toHaveCSS('text-shadow','none');
 await canvas.locator('.tb-outline-echo h1').click();
 await page.getByLabel('Selected text').fill('A page made of type');
 await page.getByRole('button',{name:'Apply text',exact:true}).click();
 await page.getByRole('button',{name:'Add Headline · Bold Stack',exact:true}).click();
 await expect(canvas.locator('h1')).toHaveCount(1);
 await expect(canvas.locator('.tb-bold-stack')).toHaveCSS('background-color','rgb(17, 18, 17)');
 await expect(canvas.locator('.tb-bold-stack h2')).toBeVisible();
 await page.getByLabel('Section category').selectOption('content');
 await page.getByRole('button',{name:'Add Features · Oversized Numbers',exact:true}).click();
 await expect(canvas.locator('[data-styled-text-block]')).toHaveCount(3);
 await expect(canvas.locator('img')).toHaveCount(0);
 await page.getByRole('button',{name:'Mobile preview',exact:true}).click();
 await expect.poll(()=>canvas.locator('.tb-offset-features .tb-numbered').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(2);
 await page.getByRole('button',{name:'Save project',exact:true}).click();
 await page.reload();
 await expect(canvas.locator('.tb-outline-echo h1')).toHaveText('A page made of type');
 await expect(canvas.locator('[data-styled-text-block]')).toHaveCount(3);
 await page.getByRole('button',{name:'Export site',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download website ZIP',exact:true}).click();
 const zip=await JSZip.loadAsync(await fs.readFile(await (await download).path()));
 expect(await zip.file('index.html').async('string')).toContain('A page made of type');
 const css=await zip.file('styles.css').async('string');
 expect(css).toContain('.tb-bold-stack');expect(css).toContain('.tb-offset-features');
});
