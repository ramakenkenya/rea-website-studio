import {test,expect} from '@playwright/test';
import JSZip from 'jszip';
import fs from 'node:fs/promises';
test('business brief, real editor, save/reload, project restore and independent export',async({page,context},testInfo)=>{
 await page.goto('/');
 await expect(page.getByRole('button',{name:'Save project',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'New website',exact:true}).click();
 await page.getByLabel('Business name').fill('Border Design');
 await page.getByLabel('What do you do?').fill('Considered interiors for homes in Malaba.');
 await page.getByLabel('Services, separated by commas').fill('Interiors, Planning, Styling');
 await page.getByLabel('Contact email').fill('hello@borderdesign.example');
 await page.getByRole('button',{name:'Create website',exact:true}).click();
 const canvas=page.frameLocator('.gjs-frame');
 await expect(canvas.locator('h1')).toContainText('Border Design');
 await canvas.locator('h1').click();
 await page.getByLabel('Selected text').fill('Spaces with a story.');
 await page.getByRole('button',{name:'Apply text',exact:true}).click();
 await expect(canvas.locator('h1')).toHaveText('Spaces with a story.');
 await page.getByRole('button',{name:'Add About section',exact:true}).click();
 await expect(canvas.locator('[data-section="About"]')).toHaveCount(2);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await expect(canvas.locator('[data-section="About"]')).toHaveCount(1);
 await page.getByRole('button',{name:'Save project',exact:true}).click();
 await expect(page.locator('#save-status')).toHaveText('Saved on this device');
 const backupEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Project backup',exact:true}).click();
 const backup=await backupEvent;const backupPath=await backup.path();
 const json=JSON.parse(await fs.readFile(backupPath,'utf8'));
 expect(json.brief.name).toBe('Border Design');expect(json.project.pages.length).toBe(1);
 await page.reload();await expect(page.frameLocator('.gjs-frame').locator('h1')).toHaveText('Spaces with a story.');
 await page.locator('#restore-file').setInputFiles(backupPath);
 await expect(page.getByRole('status')).toContainText('Project restored');
 await page.getByRole('button',{name:'Checks',exact:true}).click();
 await expect(page.locator('#quality-results')).toContainText('One main heading');
 const exportEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download website ZIP',exact:true}).click();
 const file=await exportEvent;const zip=await JSZip.loadAsync(await fs.readFile(await file.path()));
 const html=await zip.file('index.html').async('string');const css=await zip.file('styles.css').async('string');
 expect(css).toContain('@media');expect(html).toContain('Spaces with a story.');
 const standalone=await context.newPage();
 await standalone.route('https://export.example/**',async route=>route.fulfill({contentType:route.request().url().endsWith('styles.css')?'text/css':'text/html',body:route.request().url().endsWith('styles.css')?css:html}));
 await standalone.goto('https://export.example/');
 await expect(standalone.locator('h1')).toHaveText('Spaces with a story.');
 await expect(standalone.locator('.hero-art img')).toBeVisible();
 expect(await standalone.locator('.hero-art img').evaluate(el=>el.complete&&el.naturalWidth>0)).toBe(true);
 await page.getByRole('button',{name:'Build',exact:true}).click();
 await page.screenshot({path:testInfo.outputPath('studio-desktop.png'),fullPage:true});
});
test('mobile controls, section reorder, safe restore and no horizontal overflow',async({page},testInfo)=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await expect(page.getByRole('button',{name:'Save project',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Sections',exact:true}).click();
 await page.getByRole('button',{name:'Add About section',exact:true}).click();
 await expect(page.frameLocator('.gjs-frame').locator('[data-section="About"]')).toHaveCount(2);
 await page.getByRole('button',{name:'Layers',exact:true}).click();
 const move=page.getByRole('button',{name:'Move About up',exact:true}).last();await move.click();
 await expect(page.locator('#layers button[data-action="select"]').last()).toContainText('Footer');
 await page.locator('#restore-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{broken')});
 await expect(page.getByRole('status')).toContainText('Could not restore');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:testInfo.outputPath('studio-mobile.png'),fullPage:true});
});
