test('dropping Picture to Text opens the upload controls and saves characters',async({page},testInfo)=>{
 await page.goto('./?sample=rama-studio');await expect(page.locator('#save')).toBeEnabled();
 await page.locator('#new-site').click();await page.getByLabel('Business name').fill('Independent Maker');await page.getByLabel('What do you do?').fill('I make useful things.');
 await page.getByRole('radio',{name:'Text only',exact:true}).check();await page.locator('#brief-submit').click();
 const canvas=page.frameLocator('.gjs-frame');
 await expect(canvas.locator('.tp-hero h1')).toHaveText(/RAMA\s*KEN/);
 const card=page.getByRole('button',{name:'Add Picture to Text',exact:true});
 await card.scrollIntoViewIfNeeded();
 const from=await card.boundingBox(),frame=await page.locator('.gjs-frame').boundingBox();
 await page.mouse.move(from.x+from.width/2,from.y+from.height-20);
 await page.mouse.down();
 await page.mouse.move(frame.x+frame.width*.42,frame.y+137,{steps:18});
 await page.mouse.up();
 await expect(canvas.locator('.tp-page main > [data-text-section="picture"]')).toHaveCount(1);
 const art=canvas.locator('[data-text-section="picture"] .tp-art');
 await expect(page.locator('#portrait-controls')).toBeVisible();
 const before=await art.textContent();
 await page.locator('#portrait-file').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('not a picture')});
 await expect(page.getByRole('status')).toContainText('could not be read');expect(await art.textContent()).toBe(before);
 // A small deterministic PNG exercises the browser's real decoder and converter.
 const png=await page.evaluate(async()=>{const c=document.createElement('canvas');c.width=100;c.height=100;const x=c.getContext('2d');x.fillStyle='#fff';x.fillRect(0,0,100,100);x.fillStyle='#000';x.fillRect(20,10,60,80);return c.toDataURL().split(',')[1];});
 await page.locator('#portrait-file').setInputFiles({name:'portrait.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await expect(page.locator('#apply-picture-text')).toBeEnabled();
 expect(await art.textContent()).toBe(before);
 await page.selectOption('#picture-density','120');
 await expect(page.locator('#apply-picture-text')).toBeEnabled();
 await page.locator('#apply-picture-text').click();
 await expect(page.getByRole('status')).toContainText('Text artwork applied');
 const after=await art.textContent();expect(after).not.toBe(before);expect(after.split('\n')).toHaveLength(88);
 await page.locator('#portrait-description').fill('Portrait of Independent Maker');await page.locator('#portrait-description').blur();
 await page.locator('#save').click();await page.reload();
 expect(await art.textContent()).toBe(after);await expect(art).toHaveAttribute('aria-label','Portrait of Independent Maker');
 await page.screenshot({path:testInfo.outputPath('editor-text-theme.png'),fullPage:true});
});

